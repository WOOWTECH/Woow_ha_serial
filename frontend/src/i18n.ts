export type Translate = (key: Key, vars?: Record<string, string | number>) => string;

export function makeTranslate(language: string): Translate {
  const dict: Record<Key, string> = language.toLowerCase().startsWith("zh") ? zh : en;
  return (key, vars) => {
    let text = dict[key] ?? en[key] ?? key;
    if (vars) {
      for (const [name, value] of Object.entries(vars)) {
        text = text.split(`{${name}}`).join(String(value));
      }
    }
    return text;
  };
}

const CHECKSUMS: Record<string, string> = {
  crc16_modbus: "CRC16/Modbus",
  crc16_ccitt: "CRC16/CCITT",
  crc16_xmodem: "CRC16/XMODEM",
  sum16: "SUM16",
  crc8: "CRC8",
  crc8_maxim: "CRC8/Maxim",
  xor8: "XOR8",
  sum8: "SUM8",
  sum8_neg: "SUM8",
};

/** "sum8_neg@1" -> "SUM8 two's complement, from byte 2". */
export function checksumLabel(label: string, t: Translate): string {
  const [name, start] = label.split("@");
  let text = CHECKSUMS[name] ?? name;
  if (name === "sum8_neg") {
    text += ` ${t("checksum_2c")}`;
  }
  return start ? `${text} · ${t("from_byte", { n: Number(start) + 1 })}` : text;
}

export function ago(time: number, t: Translate): string {
  const seconds = Math.max(0, Date.now() / 1000 - time);
  if (seconds < 5) return t("just_now");
  if (seconds < 60) return t("s_ago", { n: Math.floor(seconds) });
  if (seconds < 3600) return t("m_ago", { n: Math.floor(seconds / 60) });
  if (seconds < 86400) return t("h_ago", { n: Math.floor(seconds / 3600) });
  return t("d_ago", { n: Math.floor(seconds / 86400) });
}

export function clock(time: number): string {
  const d = new Date(time * 1000);
  const pad = (n: number, w = 2) => String(n).padStart(w, "0");
  return `${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}.${pad(d.getMilliseconds(), 3)}`;
}

export function isKey(key: string): key is Key {
  return key in en;
}

/** "device:<id>" shows the device's name when the panel knows it. */
export function originLabel(origin: string | null, t: Translate, deviceName?: (id: string) => string | undefined): string {
  if (!origin) return t("origin_unknown");
  if (origin.startsWith("device:")) return deviceName?.(origin.split(":")[1]) ?? t("origin_device");
  const key = `origin_${origin}`;
  return isKey(key) ? t(key) : origin;
}

/** A coded backend error (DeviceError / TemplateError) in the user's language. */
export function explain(error: { code: string; [key: string]: unknown }, t: Translate): string {
  const vars: Record<string, string | number> = {};
  for (const [name, value] of Object.entries(error)) {
    if (name !== "code") vars[name] = typeof value === "number" ? value : String(value);
  }
  if (typeof error.template_code === "string") {
    const inner = `tpl_${error.template_code}`;
    vars.template = isKey(inner) ? t(inner, vars) : error.template_code;
  }
  for (const key of [`dev_${error.code}`, `tpl_${error.code}`]) {
    if (isKey(key)) return t(key, vars);
  }
  return `${error.code} ${JSON.stringify(vars)}`;
}
